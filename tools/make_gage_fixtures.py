"""Regenerate the independent-oracle fixtures for the Gage R&R tests.

This is a developer tool, not part of the application. It needs ``statsmodels``
(deliberately NOT a runtime or CI dependency):

    pip install statsmodels
    python tools/make_gage_fixtures.py

What it does
------------
1. Simulates two crossed studies from a random-effects model with known
   components and writes them, rounded to 3 decimals like real gauge
   readings, to ``tests/fixtures/gage_synthetic_*.csv``.
2. Fits ``y ~ C(part) * C(operator)`` with statsmodels OLS and records the
   ANOVA sums of squares and degrees of freedom, plus the interaction F and
   p-value (F_PO = MS_PO / MS_E is the same in the fixed- and random-effects
   models; the main-effect F tests are not, so they are not used).
3. Writes those numbers to ``tests/fixtures/gage_oracle.py``.

The tests then compare :func:`app.msa.anova.anova_gage_rr` against these
stored numbers, so CI checks the implementation against an independent one
without installing statsmodels.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels
import statsmodels.formula.api as smf
from statsmodels.stats.anova import anova_lm

ROOT = Path(__file__).resolve().parent.parent
FIX = ROOT / "tests" / "fixtures"

# name: (parts, operators, trials, sd_part, sd_operator, sd_interaction, sd_error, seed)
CASES = {
    "10x3x3_interaction": (10, 3, 3, 2.0, 0.3, 0.25, 0.25, 20261013),
    "10x3x2_pooled": (10, 3, 2, 1.0, 0.05, 0.0, 0.3, 20261014),
}

SOURCES = {
    "Part": "C(part)",
    "Operator": "C(operator)",
    "Part x Operator": "C(part):C(operator)",
    "Repeatability": "Residual",
}


def simulate(p: int, o: int, r: int, sp: float, so: float, si: float, se: float, seed: int) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    part = rng.normal(0.0, sp, p)
    oper = rng.normal(0.0, so, o)
    inter = rng.normal(0.0, si, (p, o)) if si > 0 else np.zeros((p, o))
    y = 25.0 + part[:, None, None] + oper[None, :, None] + inter[:, :, None] + rng.normal(0.0, se, (p, o, r))
    rows = [
        (f"P{i + 1:02d}", f"Op{chr(65 + j)}", k + 1, round(float(y[i, j, k]), 3))
        for i in range(p)
        for j in range(o)
        for k in range(r)
    ]
    return pd.DataFrame(rows, columns=["part", "operator", "trial", "value"])


def main() -> None:
    lines = [
        '"""Independent ANOVA oracle (statsmodels) for the Gage R&R tests.',
        "",
        "GENERATED by tools/make_gage_fixtures.py -- do not edit by hand.",
        f"statsmodels {statsmodels.__version__}, numpy {np.__version__}, pandas {pd.__version__}.",
        '"""',
        "",
        "ORACLE = {",
    ]
    for name, (p, o, r, sp, so, si, se, seed) in CASES.items():
        df = simulate(p, o, r, sp, so, si, se, seed)
        csv = FIX / f"gage_synthetic_{name}.csv"
        df.to_csv(csv, index=False, lineterminator="\n")
        fit = smf.ols("value ~ C(part) * C(operator)", data=df).fit()
        table = anova_lm(fit, typ=2)
        lines.append(f'    "{name}": {{')
        lines.append(f'        "csv": "{csv.name}",')
        for ours, theirs in SOURCES.items():
            ss = float(table.loc[theirs, "sum_sq"])
            dof = int(table.loc[theirs, "df"])
            lines.append(f'        "{ours}": {{"ss": {ss!r}, "df": {dof}}},')
        f_int = float(table.loc["C(part):C(operator)", "F"])
        p_int = float(table.loc["C(part):C(operator)", "PR(>F)"])
        lines.append(f'        "interaction_F": {f_int!r},')
        lines.append(f'        "interaction_p": {p_int!r},')
        lines.append("    },")
        print(f"{name}: wrote {csv.name}; interaction p = {p_int:.4g}")
    lines.append("}")
    (FIX / "gage_oracle.py").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
